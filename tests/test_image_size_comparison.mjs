import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { build } from 'esbuild';
const compiled=await build({entryPoints:['src/pages/Admin/ImageSizeComparison.tsx'],bundle:true,platform:'node',format:'cjs',packages:'external',jsx:'automatic',write:false,alias:{'@':new URL('../src',import.meta.url).pathname}});
const module={exports:{}};
new Function('require','module','exports',compiled.outputFiles[0].text)(createRequire(import.meta.url),module,module.exports);
const { ImageSizeComparison, formatImageSize }=module.exports;
const React=createRequire(import.meta.url)('react');
const {renderToStaticMarkup}=createRequire(import.meta.url)('react-dom/server');
assert.equal(formatImageSize(1536,'en'),'1.5 KB');
assert.equal(formatImageSize(1048576,'en'),'1 MB');
assert.equal(formatImageSize(12,'en'),'12 B');
let html=renderToStaticMarkup(React.createElement(ImageSizeComparison,{lang:'en',sizes:{originalBytes:1048576,uploadedBytes:262144}}));
assert.match(html,/Before/); assert.match(html,/1 MB/); assert.match(html,/After/); assert.match(html,/256 KB/); assert.match(html,/Saved/); assert.match(html,/75%/);
html=renderToStaticMarkup(React.createElement(ImageSizeComparison,{lang:'ar',sizes:{originalBytes:51200,uploadedBytes:51200}}));
assert.match(html,/قبل الضغط/); assert.match(html,/بعد الضغط/); assert.match(html,/بدون تغيير/); assert.doesNotMatch(html,/توفير/);
const editor=readFileSync('src/pages/Admin/ProductImagesEditor.tsx','utf8');
assert.match(editor,/sizesByUrl\[src\] && <ImageSizeComparison sizes=\{sizesByUrl\[src\]\}/);
assert.match(editor,/\[result.url\]: \{ originalBytes: result.originalBytes, uploadedBytes: result.uploadedBytes \}/);
assert.match(editor,/filter\(\(\[url\]\) => next\.includes\(url\)\)/);
assert.match(editor,/لهذه الرفعة فقط/);
console.log('Image size comparison: before, after, unchanged, per-image association and removal checks passed.');
