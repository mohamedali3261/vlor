import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
const buildResult = await build({ entryPoints: ['tests/storefront_render_fixture.tsx'], bundle: true, platform: 'node', format: 'cjs', packages: 'external', jsx: 'automatic', write: false, alias: { '@': new URL('../src', import.meta.url).pathname } });
const module = { exports: {} };
new Function('require', 'module', 'exports', buildResult.outputFiles[0].text)(createRequire(import.meta.url), module, module.exports);
const { renderStudioSettingsAndImages, mergeContent } = module.exports;
const html = renderStudioSettingsAndImages(125);
assert.match(html, /class="studio-product-preview/); assert.match(html, /transform:scale\(1\.25\)/);
assert.match(html, /type="range"[^>]+min="50"[^>]+max="150"/);
assert.match(html, /ولن يُظهر الصور في الموقع/);
assert.match(html, /رابط فيسبوك/); assert.match(html, /رابط يوتيوب/);
assert.doesNotMatch(html, />Email<|>Hours \(English\)<|>المواعيد \(عربي\)</);
assert.match(renderStudioSettingsAndImages(100, false), /لا توجد صورة متاحة/);
assert.equal(mergeContent(null).theme.productImageScale, 100);
assert.equal(mergeContent({theme:{productImageScale:125}}).theme.productImageScale, 125);
assert.equal(mergeContent({theme:{productImageScale:1000}}).theme.productImageScale, 150);
assert.equal(mergeContent({theme:{productImageScale:2}}).theme.productImageScale, 50);
assert.equal(mergeContent({theme:{productImageScale:null}}).theme.productImageScale, 100);
assert.equal(mergeContent({theme:{productImageScale:'oops'}}).theme.productImageScale, 100);
const saved = mergeContent({theme:{productImageScale:130}});
assert.equal(mergeContent(JSON.parse(JSON.stringify(saved))).theme.productImageScale, 130);
const content = readFileSync('src/pages/Admin/ContentEditor.tsx', 'utf8');
assert.doesNotMatch(content, /key: "story"/); assert.match(content, /next\.theme\.productImageScale = value/);
const form = readFileSync('src/pages/Admin/ProductForm.tsx', 'utf8');
assert.doesNotMatch(form, /if \(!draft\.images\.trim\(\)\)/); assert.match(form, /صور المنتج \(اختياري\)/);
assert.match(form, /images: draft\.images\.split/);
const css = readFileSync('src/styles/product-card.css', 'utf8');
assert.match(css, /height: 350px/); assert.match(css, /max-width: 275px/); assert.match(css, /:focus-within/);
assert.match(readFileSync('src/index.css','utf8'), /img\.brand-logo, img\.studio-product-preview/);
assert.doesNotMatch(readFileSync('src/components/product/ProductCard.tsx','utf8'), /<img\b/);
console.log('Smaller cards, studio-only image preview, settings cleanup and persistence tests passed.');
