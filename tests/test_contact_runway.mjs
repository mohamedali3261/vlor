import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { build } from 'esbuild';

const compiled = await build({ entryPoints: ['tests/storefront_render_fixture.tsx'], loader: { '.css': 'empty' }, bundle: true, platform: 'node', format: 'cjs', packages: 'external', jsx: 'automatic', write: false, alias: { '@': new URL('../src', import.meta.url).pathname } });
const module = { exports: {} };
new Function('require', 'module', 'exports', compiled.outputFiles[0].text)(createRequire(import.meta.url), module, module.exports);
const { renderContactAndFooter, mergeContent, runwayWheel, socialUrl } = module.exports;
const storage = new Map();
globalThis.window = { localStorage: { getItem: (key) => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) } };
let html = renderContactAndFooter();
assert.match(html, /wa\.me\/201276163222/);
assert.match(html, /tel:01276163222/);
assert.doesNotMatch(html, /mailto:|hello@vlor|١١:٠٠|أسئلتك، والإجابات|الشحن والاستبدال/);
for (const label of ['WhatsApp', 'Facebook', 'Instagram', 'TikTok']) assert.match(html, new RegExp(`aria-label="${label}`));
assert.match(html, /social-link--whatsapp/); assert.match(html, /social-link--facebook/); assert.match(html, /social-link--instagram/); assert.match(html, /social-link--tiktok/);
assert.match(html, /href="https:\/\/www\.facebook\.com\/share\/1FyisBgKu9\/?\?mibextid=wwXIfr"/);
assert.match(html, /href="https:\/\/www\.tiktok\.com\/@vlor\.perfumes"/);
assert.doesNotMatch(html, /aria-label="YouTube/);
const version = '.20261103170000';
storage.set('malika.settings.v2' + version, JSON.stringify({ whatsapp: 'old-number', phone: 'old-phone', instagram: 'existing', freeShippingThreshold: 42 }));
html = renderContactAndFooter();
assert.match(html, /wa\.me\/201276163222/); assert.match(html, /tel:01276163222/); assert.match(html, /instagram\.com\/existing/);
storage.set('malika.settings.v3' + version, JSON.stringify({ whatsapp: '201111111111', phone: '01111111111', instagram: 'existing', facebook: 'https://facebook.com/myshop', youtube: 'https://youtube.com/@myshop' }));
html = renderContactAndFooter();
assert.match(html, /wa\.me\/201111111111/); assert.match(html, /tel:01111111111/);
assert.match(html, /href="https:\/\/facebook\.com\/myshop"/); assert.doesNotMatch(html, /href="https:\/\/youtube\.com\/@myshop"/);
assert.equal(socialUrl('', 'youtube'), undefined);
assert.equal(socialUrl('https://evil.com', 'facebook'), undefined);
assert.equal(socialUrl('javascript:alert(1)', 'youtube'), undefined);
assert.equal(socialUrl('@myshop', 'instagram'), 'https://instagram.com/myshop');
const oldAr = 'عطور تُركَّب لمن يُذكَرون قبل أن يتكلّموا. تُمزج ببطء، بكميات صغيرة — صُنعت بعناية.';
const oldEn = 'Extraits composed for people who are remembered before they speak. Blended slowly, in small batches — made with care.';
let merged = mergeContent({ hero: { lead: { ar: oldAr, en: 'My own wording' } } });
assert.notEqual(merged.hero.lead.ar, oldAr); assert.equal(merged.hero.lead.en, 'My own wording');
merged = mergeContent({ hero: { lead: { ar: 'نص خاص', en: oldEn } } });
assert.equal(merged.hero.lead.ar, 'نص خاص'); assert.notEqual(merged.hero.lead.en, oldEn);
assert.deepEqual(runwayWheel(0, 7, -50), { target: 0, consume: false });
assert.deepEqual(runwayWheel(7, 7, 50), { target: 7, consume: false });
assert.equal(runwayWheel(0, 7, 120).consume, true);
assert.equal(runwayWheel(7, 7, -120).consume, true);
assert.equal(runwayWheel(0, 0, 120).consume, false);
const runway = readFileSync('src/pages/Home/RunwayLookbook.tsx', 'utf8');
assert.doesNotMatch(runway, /مجموعة التوقيع الملكية|wrap\(/);
assert.match(runway, /idx === activeIdx/);
assert.match(runway, /touch|onPointerMove/); assert.match(runway, /onKeyDown/);
const product = readFileSync('src/pages/Product/ProductPage.tsx', 'utf8');
assert.doesNotMatch(product, /PurchaseBar|h-28 lg:hidden/); assert.match(product, /<PurchasePanel/);
delete globalThis.window;
console.log('Contact, legacy settings, social links, hero copy and bounded runway tests passed.');
