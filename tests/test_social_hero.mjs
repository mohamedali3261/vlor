import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
const compiled = await build({ entryPoints: ['tests/storefront_render_fixture.tsx'], loader: { '.css': 'empty' }, bundle: true, platform: 'node', format: 'cjs', packages: 'external', jsx: 'automatic', write: false, alias: { '@': new URL('../src', import.meta.url).pathname } });
const module = { exports: {} };
new Function('require', 'module', 'exports', compiled.outputFiles[0].text)(createRequire(import.meta.url), module, module.exports);
const { renderSocialAndHero, migrateSocialSettings, defaultSettings, socialUrl } = module.exports;
const data = new Map();
const storage = { getItem: (key) => data.get(key) ?? null, setItem: (key, value) => data.set(key, String(value)) };
globalThis.window = { localStorage: storage, matchMedia: () => ({ matches: false }) };
const key = 'malika.settings.v3.20261103170000';
data.set(key, JSON.stringify({ whatsapp: '201111111111', instagram: 'custominsta', facebook: '', youtube: '', freeShippingThreshold: 42, address: { en: 'mine', ar: 'ع' } }));
migrateSocialSettings(storage, key, defaultSettings);
let settings = JSON.parse(data.get(key));
assert.equal(settings.facebook, defaultSettings.facebook);
assert.equal(settings.youtube, defaultSettings.youtube);
assert.equal(settings.tiktok, defaultSettings.tiktok);
assert.equal(settings.instagram, 'custominsta');
assert.equal(settings.whatsapp, '201111111111');
assert.equal(settings.freeShippingThreshold, 42);
assert.equal(settings.address.en, 'mine');
let html = renderSocialAndHero();
assert.equal((html.match(/social-links--hero/g) || []).length, 1);
for (const name of ['Facebook', 'WhatsApp', 'Instagram', 'TikTok']) assert.equal((html.match(new RegExp(`aria-label="${name}"`, 'g')) || []).length, 2);
assert.match(html, /www\.facebook\.com\/share\/1FyisBgKu9\/\?mibextid=wwXIfr/);
assert.match(html, /www\.tiktok\.com\/@vlor\.perfumes/);
assert.match(html, /instagram\.com\/custominsta/);
assert.match(html, /wa\.me\/201111111111/);
assert.doesNotMatch(html, /aria-label="YouTube/);
settings.facebook = 'https://facebook.com/custom'; settings.tiktok = 'https://www.tiktok.com/@custom'; settings.youtube = 'https://youtube.com/@custom'; settings.instagram = ''; settings.whatsapp = '';
data.set(key, JSON.stringify(settings));
migrateSocialSettings(storage, key, defaultSettings);
html = renderSocialAndHero();
assert.match(html, /href="https:\/\/facebook\.com\/custom"/);
assert.match(html, /href="https:\/\/www\.tiktok\.com\/@custom"/);
assert.match(html, /aria-label="Instagram الرابط غير متاح"/);
assert.match(html, /aria-label="WhatsApp الرابط غير متاح"/);
assert.doesNotMatch(html, /href="https:\/\/youtube\.com\/@custom"/);
settings.facebook = ''; settings.tiktok = ''; settings.youtube = '';
data.set(key, JSON.stringify(settings));
migrateSocialSettings(storage, key, defaultSettings);
assert.equal(JSON.parse(data.get(key)).facebook, '');
assert.equal(JSON.parse(data.get(key)).tiktok, '');
assert.equal(JSON.parse(data.get(key)).youtube, '');
assert.equal(socialUrl('www.tiktok.com/@vlor.perfumes', 'tiktok'), 'https://www.tiktok.com/@vlor.perfumes');
assert.equal(socialUrl('@shop', 'tiktok'), 'https://tiktok.com/@shop');
assert.equal(socialUrl('https://evil.com/@shop', 'tiktok'), undefined);
assert.equal(socialUrl('javascript:alert(1)', 'tiktok'), undefined);
const form = readFileSync('src/pages/Admin/StoreSettingsForm.tsx', 'utf8');
for (const field of ['whatsapp', 'instagram', 'facebook', 'tiktok', 'youtube']) assert.match(form, new RegExp(`set\\("${field}"`));
assert.match(form, /registerDraft/);
delete globalThis.window;
console.log('Hero and footer social links, studio settings and one-time migration checks passed.');
