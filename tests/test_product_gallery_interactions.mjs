import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
const require=createRequire(import.meta.url);
const React=require('react');
const TestRenderer=require('react-test-renderer');
const {act}=TestRenderer;
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
const bundle=await build({ entryPoints:['src/pages/Product/Gallery.tsx'], bundle:true, platform:'node', format:'cjs', packages:'external', jsx:'automatic', write:false, loader:{'.css':'empty'}, alias:{'@':new URL('../src',import.meta.url).pathname}, plugins:[{name:'mock-language',setup(build){build.onResolve({filter:/^@\/i18n\/LanguageContext$/},()=>({path:'lang',namespace:'mock'})); build.onLoad({filter:/.*/,namespace:'mock'},()=>({contents:'exports.useLang = () => ({lang:"en",l:v=>v.en,x:(en)=>en})',loader:'js'}));}}] });
const module={exports:{}}; new Function('require','module','exports',bundle.outputFiles[0].text)(require,module,module.exports);
const {Gallery}=module.exports;
let timers=new Map(),nextTimer=0, visibilityHandler, mediaHandler;
const media={matches:false,addEventListener:(_e,cb)=>{mediaHandler=cb;},removeEventListener:()=>{mediaHandler=undefined;}};
globalThis.window={matchMedia:()=>media,setTimeout:(fn,delay)=>{assert.equal(delay,5000);timers.set(++nextTimer,fn);return nextTimer;},clearTimeout:(id)=>timers.delete(id)};
globalThis.document={hidden:false,addEventListener:(event,handler)=>{if(event==='visibilitychange')visibilityHandler=handler;},removeEventListener:()=>{visibilityHandler=undefined;}};
const product={id:'p1',name:{en:'Scent',ar:'عطر'},tagline:{en:'scent',ar:'عطر'},images:['/main.png','/other.png','/last.png'],cutout:'/legacy.png'};
let renderer;
await act(async()=>{renderer=TestRenderer.create(React.createElement(Gallery,{product}));});
const root=renderer.root;
const stage=()=>root.findByProps({className:'product-gallery__stage'});
const image=()=>root.findByProps({className:'product-gallery__image'});
const byLabel=(label)=>root.findByProps({'aria-label':label});
const tick=async()=>{const entries=[...timers]; assert.equal(entries.length,1);timers.delete(entries[0][0]);await act(async()=>entries[0][1]());};
assert.equal(image().props.src,'/main.png');
assert.equal(root.findAllByType('img').length,4); // main plus all thumbnails
assert.equal(byLabel('Image 1 · Main').props['aria-pressed'],true);
await tick(); assert.equal(image().props.src,'/other.png');
await act(async()=>root.findByType('section').props.onMouseEnter()); assert.equal(timers.size,0);
await act(async()=>byLabel('Image 3').props.onClick()); assert.equal(image().props.src,'/last.png');
await act(async()=>byLabel('Previous image').props.onClick()); assert.equal(image().props.src,'/other.png');
await act(async()=>image().props.onLoad());
await act(async()=>stage().props.onPointerMove({pointerType:'mouse',clientX:80,clientY:45,currentTarget:{getBoundingClientRect:()=>({left:0,top:5,width:100,height:100})}}));
let layer=root.findByProps({className:'product-gallery__zoom-layer'});
assert.equal(layer.props['data-zoomed'],true); assert.equal(layer.props.style['--zoom-x'],'80%'); assert.equal(layer.props.style['--zoom-y'],'40%');
await act(async()=>stage().props.onPointerLeave()); assert.equal(root.findByProps({className:'product-gallery__zoom-layer'}).props['data-zoomed'],false);
await act(async()=>stage().props.onPointerMove({pointerType:'touch',clientX:80,clientY:45,currentTarget:{getBoundingClientRect:()=>({left:0,top:0,width:100,height:100})}}));
assert.equal(root.findByProps({className:'product-gallery__zoom-layer'}).props['data-zoomed'],false);
await act(async()=>root.findByType('section').props.onMouseLeave()); assert.equal(timers.size,1);
await act(async()=>byLabel('Pause automatic image rotation').props.onClick()); assert.equal(timers.size,0);
await act(async()=>byLabel('Play automatic image rotation').props.onClick()); assert.equal(timers.size,1);
await act(async()=>{document.hidden=true;visibilityHandler();}); assert.equal(timers.size,0);
await act(async()=>{document.hidden=false;visibilityHandler();}); assert.equal(timers.size,1);
await act(async()=>root.findByType('section').props.onFocus()); assert.equal(timers.size,0);
await act(async()=>root.findByType('section').props.onBlur({currentTarget:{contains:()=>false},relatedTarget:null})); assert.equal(timers.size,1);
await act(async()=>{media.matches=true;mediaHandler();}); assert.equal(timers.size,0);
assert.ok(byLabel('Play automatic image rotation'));
await act(async()=>renderer.update(React.createElement(Gallery,{product:{...product,id:'p2',images:['/new.png']}})));
assert.equal(image().props.src,'/new.png'); assert.equal(timers.size,0); assert.equal(root.findAllByProps({'aria-label':'Next image'}).length,0);
await act(async()=>renderer.unmount()); assert.equal(timers.size,0);assert.equal(visibilityHandler,undefined);assert.equal(mediaHandler,undefined);
console.log('Gallery rotation, controls, visibility, focus, pointer zoom, reduced motion and cleanup passed.');
